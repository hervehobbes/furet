BeforeAll {
    Import-Module (Join-Path $PSScriptRoot '..\CommitMessage.psm1') -Force
}

Describe 'Test-CommitSubject' {
    It 'accepts a valid subject' {
        $result = Test-CommitSubject 'fix: keep the selection after a paste'
        $result | Should -Be $null
    }

    It 'accepts a scope made of lowercase letters, digits and hyphens' {
        $result = Test-CommitSubject 'fix(quick-search2): keep the selection'
        $result | Should -Be $null
    }

    It 'accepts the breaking-change marker' {
        $result = Test-CommitSubject 'feat(api)!: drop the legacy setting'
        $result | Should -Be $null
    }

    It 'accepts merge commits generated by git' {
        $result = Test-CommitSubject "Merge branch 'feature' into main"
        $result | Should -Be $null
    }

    It 'accepts merge commits even when they mention a rejected word' {
        $result = Test-CommitSubject "Merge branch 'lot-3' into main"
        $result | Should -Be $null
    }

    It 'accepts revert commits generated by git' {
        $result = Test-CommitSubject 'Revert "fix(search): keep the selection"'
        $result | Should -Be $null
    }

    It 'accepts fixup commits generated by git' {
        $result = Test-CommitSubject 'fixup! feat: add the hotkey'
        $result | Should -Be $null
    }

    It 'rejects an unknown type' {
        $result = Test-CommitSubject 'wip: keep the selection'
        $result | Should -Not -Be $null
    }

    It 'rejects a subject longer than 71 characters after the colon' {
        $result = Test-CommitSubject ('feat: ' + ('a' * 72))
        $result | Should -Not -Be $null
    }

    It 'accepts a subject of exactly 71 characters after the colon' {
        $result = Test-CommitSubject ('feat: ' + ('a' * 71))
        $result | Should -Be $null
    }

    It 'rejects the word lot in the subject' {
        $result = Test-CommitSubject 'feat: add a lot of tests'
        $result | Should -Not -Be $null
    }

    It 'rejects the word lot in the scope' {
        $result = Test-CommitSubject 'feat(lot): add the search'
        $result | Should -Not -Be $null
    }

    It 'accepts words that only contain lot' {
        $result = Test-CommitSubject 'fix: keep the slot selection'
        $result | Should -Be $null
    }

    It 'rejects the word Prompt written with a capital letter' {
        $result = Test-CommitSubject 'fix: Prompt editor crash'
        $result | Should -Not -Be $null
    }

    It 'rejects a subject ending with a period' {
        $result = Test-CommitSubject 'fix: keep the selection.'
        $result | Should -Not -Be $null
    }

    It 'rejects an uppercase type' {
        $result = Test-CommitSubject 'Feat: add the hotkey'
        $result | Should -Not -Be $null
    }

    It 'rejects a missing space after the colon' {
        $result = Test-CommitSubject 'feat:add the hotkey'
        $result | Should -Not -Be $null
    }

    It 'rejects an empty message' {
        $result = Test-CommitSubject ''
        $result | Should -Not -Be $null
    }

    It 'rejects a message made of spaces' {
        $result = Test-CommitSubject '   '
        $result | Should -Not -Be $null
    }

    It 'checks only the first line of a multi-line message' {
        $result = Test-CommitSubject "feat: add the hotkey`n`nThis body mentions the lot and a prompt."
        $result | Should -Be $null
    }

    It 'rejects a message whose first line is invalid even when a later line is valid' {
        $result = Test-CommitSubject "wip`nfeat: add the hotkey"
        $result | Should -Not -Be $null
    }

    It 'accepts a CRLF line ending' {
        $result = Test-CommitSubject "feat: keep the selection`r`n`r`nBody."
        $result | Should -Be $null
    }

    It 'rejects a trailing period followed by a CRLF line ending' {
        $result = Test-CommitSubject "fix: keep the selection.`r`n"
        $result | Should -Not -Be $null
    }
}
